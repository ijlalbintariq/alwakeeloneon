export interface StatuteRef {
  /** Short abbreviation as typed by the user, e.g. "PPC" */
  abbr: string;
  /** Full statutory name */
  fullName: string;
  /** Section or article number extracted from query, e.g. "392" */
  sectionOrArticle: string;
}

