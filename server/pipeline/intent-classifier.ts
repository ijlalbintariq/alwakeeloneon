// Matches both report-style citations (1970 SCMR 869) AND case numbers (C.A. 8-Q of 2017)
const CITATION_PATTERN = /\b(?:pld|scmr|ylr|mld|clc|plj|nlr|pcrlj|ptcl|ptd|lhc|ihc|shc|phc|bhc)\s+\d{4}|(?:19|20)\d{2}\s+(?:pld|scmr|ylr|mld|clc|plj|nlr|pcrlj|ptcl|ptd)\b|\bc\.?a\.?\s+\d+[\w\-]*\s+of\s+(?:19|20)\d{2}\b|\b(?:civil|criminal)\s+(?:appeal|petition)\s+(?:no\.?\s*)?\d+[\w\-]*\s+of\s+(?:19|20)\d{2}\b|\bwrit\s+petition\s+(?:no\.?\s*)?\d+[\w\-]*\s+of\s+(?:19|20)\d{2}\b|\br\.?p\.?a\.?\s+\d+[\w\-]*\s+of\s+(?:19|20)\d{2}\b/i;

function norm(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9\s\-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// ---------------------------------------------------------------------------
// Main classifier
// ---------------------------------------------------------------------------

export function classifyQueryIntent(rawQuery: string, context?: { module?: string }): QueryIntent {
  const raw = rawQuery.trim();
  
  // Define defaults and context overrides
  let needsCase = true;
  let needsStats = true;
  let needsAdmin = true;

  if (context?.module === "case-search") {
    needsStats = false;
    needsAdmin = false;
  } else if (context?.module === "contract-drafting" || context?.module === "legal-drafting") {
    needsCase = false; // contract/legal drafting focus on statutes/templates, not precedents
  }

  // Truncate very long queries (e.g. pasted petitions) to first ~600 chars
  // for topic detection and DB search. 600 covers 95%+ of real lawyer questions
  // (facts-then-question pattern). For truly long queries (petitions), the Tier 2
  // LLM extractor receives the full untruncated text via queryForRetrieval.
  // The full normalizedFull is kept for tail-scoring topics beyond the cutoff.
  const normalizedFull = norm(raw);
  const normalized = normalizedFull.length > 600 ? normalizedFull.slice(0, 600).trim() : normalizedFull;
  const words = normalized.split(/\s+/);

  // --- Citation lookup? (check full text so citations beyond 600 chars are detected) ---
  if (CITATION_PATTERN.test(normalizedFull)) {
    return {
      raw,
      normalized,
      type: "citation-lookup",
      topics: [],
      expandedQuery: normalized,
      expandedTerms: words,
      needsCaseLaw: true,
      needsStatutes: false,
      needsAdminDocs: false,
    };
  }

  // --- Statute section reference? (e.g. "PPC 392", "Article 25 Constitution") ---
  const statuteRef = detectStatuteRef(raw);
  if (statuteRef) {
    const expandedStat = `${statuteRef.fullName} section ${statuteRef.sectionOrArticle} ${normalized}`;
    return {
      raw,
      normalized,
      type: "general-legal",  // Not "statute" — users asking about a section also want case law on it
      topics: [],
      expandedQuery: expandedStat,
      expandedTerms: expandedStat.split(/\s+/),
      needsCaseLaw: needsCase,
      needsStatutes: needsStats,
      needsAdminDocs: needsAdmin,
      statuteRef,
    };
  }

  // --- Score each topic ---
  type ScoredTopic = { topic: LegalTopic; score: number };
  const scored: ScoredTopic[] = [];

  // Helper: Exact word boundary match to prevent "fired" matching "fir" or "nikaal" matching "murder"
  function matchesWordBoundary(text: string, term: string): boolean {
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return new RegExp(`\\b${escaped}\\b`, "i").test(text);
  }

  for (const topic of LEGAL_TOPICS) {
    let score = 0;
    // Primary term hit — strong signal (exact word boundary match)
    for (const term of topic.primary) {
      if (matchesWordBoundary(normalized, term)) score += 12;
      // Tail scoring: check beyond 600 chars at half weight for long queries
      else if (normalizedFull.length > 600 && matchesWordBoundary(normalizedFull, term)) score += 6;
    }
    // Synonym hit — weaker signal (exact word boundary match)
    for (const term of topic.synonyms) {
      if (matchesWordBoundary(normalized, term)) score += 4;
      else if (normalizedFull.length > 600 && matchesWordBoundary(normalizedFull, term)) score += 2;
    }
    // Partial word match against primary terms (only if length >= 4)
    for (const word of words) {
      if (word.length < 4) continue;
      for (const term of topic.primary) {
        if (term !== word && term.length >= 4 && (term.includes(word) || word.includes(term))) score += 2;
      }
    }
    if (score > 0) scored.push({ topic, score });
  }

  scored.sort((a, b) => b.score - a.score);
  const topTopicScore = scored.length > 0 ? scored[0].score : 0;
  let topTopics = scored.slice(0, 3).map((s) => s.topic);

  // If in contract or legal drafting context, force contract and property topics
  if (context?.module === "contract-drafting" || context?.module === "legal-drafting") {
    const contractTopic = LEGAL_TOPICS.find((t) => t.id === "contract");
    const propertyTopic = LEGAL_TOPICS.find((t) => t.id === "property");
    if (contractTopic && !topTopics.some((t) => t.id === "contract")) {
      topTopics.unshift(contractTopic);
    }
    if (propertyTopic && !topTopics.some((t) => t.id === "property")) {
      topTopics.unshift(propertyTopic);
    }
    topTopics = topTopics.slice(0, 3); // keep top 3
  }

  // --- Build expanded query ---
  const termSet = new Set<string>([normalized]);
  // Add top 2 topics' synonyms (first 6 each)
  for (const topic of topTopics.slice(0, 2)) {
    for (const t of topic.synonyms.slice(0, 6)) termSet.add(t);
    for (const t of topic.primary) termSet.add(t);
  }
  const expandedTerms = Array.from(termSet);
  // 15 terms: the DB splits these into individual tokens for ILIKE matching (storage.ts queryTokens).
  // 5 was too few — topic synonyms were truncated, missing key retrieval terms.
  const expandedQuery = expandedTerms.slice(0, 15).join(" ");

  // --- Detect intent type ---
  const statuteIndicators = ["section", "act", "ordinance", "ppc", "crpc", "statute", "provision", "law", "code"];
  const caseIndicators = ["case", "judgment", "precedent", "ruling", "court held", "citation", "appeal", "conviction"];
  let statuteScore = 0;
  let caseScore = 0;
  for (const word of words) {
    if (statuteIndicators.includes(word)) statuteScore++;
    if (caseIndicators.includes(word)) caseScore++;
  }

  let type: IntentType;
  if (caseScore > statuteScore) {
    type = "case-law";
  } else if (statuteScore > caseScore) {
    type = "statute";
  } else {
    type = "general-legal"; // retrieve both
  }

  return {
    raw,
    normalized,
    type,
    topics: topTopics,
    topTopicScore,
    expandedQuery,
    expandedTerms,
    needsCaseLaw: needsCase,
    needsStatutes: needsStats,
    needsAdminDocs: needsAdmin,
  };
}

/**
 * Cheap Query Analyzer for 3-Tier Pipeline Routing.
 * Evaluates legal explicitness + ambiguity (not character length alone).
 */
export function analyzeQueryExplicitness(query: string, intent: QueryIntent): "tier1_citation" | "tier1_section" | "tier1.5_explicit" | "tier2_narrative" {
  if (intent.type === "citation-lookup") return "tier1_citation";
  if (intent.statuteRef) return "tier1_section";

  // Tier 1.5: High legal explicitness + low ambiguity (e.g. "bail 302", "PPC 489-F cheque bounce")
  const hasHighConfidenceTopic = (intent.topTopicScore ?? 0) >= 12;
  const isShortExplicit = query.trim().length <= 150 && hasHighConfidenceTopic;

  if (isShortExplicit) {
    return "tier1.5_explicit";
  }

  // Default: Narrative / ambiguous query requiring Tier 2 LLM Research Agent
  return "tier2_narrative";
}

